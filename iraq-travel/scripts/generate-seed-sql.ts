/**
 * Generates supabase/seed.sql from the TypeScript seed data (src/data/*).
 * Usage: npm run db:seed-sql
 * Demo records keep is_demo = true so they can be removed with:
 *   delete from <table> where is_demo;
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { buildSeedStore } from "../src/data/seed";
import { TABLES } from "../src/lib/store/types";
import type { EntityName } from "../src/data/types";

const JSON_ARRAY_KEYS = new Set(["images", "actions", "days"]);
const ORDER: EntityName[] = [
  "officialSources", "governorates", "touristSites", "hotels", "restaurants", "restaurantMenus", "transportProviders", "transportRoutes",
  "tourGuides", "priceRecords", "safetyAdvisories", "emergencyContacts", "scamReports", "reviews",
];

const snake = (k: string) => k.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const pgArray = (a: unknown[]) => q(`{${a.map((v) => `"${String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`).join(",")}}`);

function lit(key: string, v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (typeof v === "string") return q(v);
  if (Array.isArray(v)) return JSON_ARRAY_KEYS.has(key) ? `${q(JSON.stringify(v))}::jsonb` : pgArray(v);
  return `${q(JSON.stringify(v))}::jsonb`;
}

const store = buildSeedStore();
const out: string[] = [
  "-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.",
  "-- Real reference content is marked verification_status = 'unverified' until editors verify it.",
  "-- DEMO rows (is_demo = true) are fictional sample data for testing only.",
  "begin;",
];
for (const entity of ORDER) {
  const rows = store[entity] as unknown as Record<string, unknown>[];
  if (!rows.length) continue;
  out.push(`\n-- ${TABLES[entity]} (${rows.length})`);
  for (const r of rows) {
    const keys = Object.keys(r).filter((k) => k !== "passwordHash");
    if (!keys.includes("isDemo")) keys.push("isDemo");
    out.push(`insert into public.${TABLES[entity]} (${keys.map(snake).join(", ")}) values (${keys.map((k) => lit(k, k === "isDemo" ? !!r.isDemo : r[k])).join(", ")}) on conflict (id) do nothing;`);
  }
}
out.push("commit;", "");
const file = path.join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file}`);
